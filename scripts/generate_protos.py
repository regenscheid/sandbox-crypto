"""Generate the policy middleware's protobuf code from the vendored OpenShell contracts.

Run ``uv run python scripts/generate_protos.py`` after changing the files in
packages/policy-middleware/proto. With ``--check``, as CI runs it, the script
changes nothing and fails when the committed code differs from what it would
generate.
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from importlib import resources
from pathlib import Path

from grpc_tools import protoc

ROOT = Path(__file__).resolve().parent.parent
PROTO_DIR = ROOT / "packages" / "policy-middleware" / "proto"
OUT_DIR = (
    ROOT / "packages" / "policy-middleware" / "src" / "sandbox_science" / "policy_middleware"
) / "_proto"
PROTOS = ("extension.proto", "supervisor_middleware.proto")
HEADER = (
    "# SPDX-License-Identifier: Apache-2.0\n"
    "# Generated by scripts/generate_protos.py from the OpenShell v0.1.3 contracts in\n"
    "# packages/policy-middleware/proto. Do not edit.\n"
)
# protoc writes imports of sibling files as top-level modules; the generated
# code lives inside a package, so they must be relative.
IMPORT_FIXES = {
    "import extension_pb2 as extension__pb2": "from . import extension_pb2 as extension__pb2",
    "import extension_pb2 as _extension_pb2": "from . import extension_pb2 as _extension_pb2",
}


def generate() -> dict[str, str]:
    """Return the generated files, by name, without touching the package."""
    well_known = resources.files("grpc_tools") / "_proto"
    with tempfile.TemporaryDirectory() as tmp:
        status = protoc.main(
            [
                "protoc",
                f"--proto_path={PROTO_DIR}",
                f"--proto_path={well_known}",
                f"--python_out={tmp}",
                f"--pyi_out={tmp}",
                *PROTOS,
            ]
        )
        if status != 0:
            raise RuntimeError(f"protoc failed with status {status}")
        files = {"__init__.py": HEADER}
        for path in sorted(Path(tmp).iterdir()):
            text = path.read_text(encoding="utf-8")
            for old, new in IMPORT_FIXES.items():
                text = text.replace(old, new)
            files[path.name] = HEADER + text
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the committed code is out of date"
    )
    args = parser.parse_args()
    expected = generate()
    present = {path.name for path in OUT_DIR.glob("*") if path.is_file()}
    if args.check:
        stale = sorted(
            name
            for name in expected.keys() | present
            if name not in expected
            or name not in present
            or (OUT_DIR / name).read_text(encoding="utf-8") != expected[name]
        )
        for name in stale:
            print(f"{OUT_DIR / name} is out of date", file=sys.stderr)
        if stale:
            print("run: uv run python scripts/generate_protos.py", file=sys.stderr)
        return 1 if stale else 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name in present - expected.keys():
        (OUT_DIR / name).unlink()
    for name, text in expected.items():
        (OUT_DIR / name).write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
