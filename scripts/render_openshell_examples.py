"""Render the example OpenShell policies in examples/openshell/.

They are compiled from examples/policy.yaml and examples/openshell/targets.yaml.
Run after changing either, or the compiler: ``uv run python
scripts/render_openshell_examples.py``. With ``--check``, report stale files
instead of writing them.
"""

from __future__ import annotations

import sys
from pathlib import Path

from sandbox_science.policy import PoolCeiling, load_policy
from sandbox_science.policy.openshell import compile_mcp_proxy, compile_sandbox, load_targets

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "examples" / "openshell"
HEADER = (
    "# Generated by scripts/render_openshell_examples.py from examples/policy.yaml\n"
    "# and examples/openshell/targets.yaml. Do not edit by hand.\n"
)


def render() -> dict[str, str]:
    """Return the example files by name."""
    policy = load_policy(ROOT / "examples" / "policy.yaml")
    targets = load_targets(OUTPUT / "targets.yaml")
    sandbox = compile_sandbox(policy, targets.sandbox)
    mcp = compile_mcp_proxy(policy, targets.mcp_proxy, ceiling=PoolCeiling.unrestricted())
    return {
        "research-sandbox.yaml": HEADER + sandbox.policy.to_yaml(),
        "mcp-proxy.yaml": HEADER + mcp.policy.to_yaml(),
    }


def main(argv: list[str]) -> int:
    stale = [
        name
        for name, text in render().items()
        if not (OUTPUT / name).exists() or (OUTPUT / name).read_text() != text
    ]
    if "--check" in argv:
        for name in stale:
            print(f"examples/openshell/{name} is out of date", file=sys.stderr)
        return 1 if stale else 0
    for name, text in render().items():
        (OUTPUT / name).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
