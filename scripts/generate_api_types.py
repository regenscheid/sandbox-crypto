HEADER = (
    "// SPDX-License-Identifier: MIT\n"
    "// Generated by scripts/generate_api_types.py from the workspace's response models.\n"
    "// Do not edit.\n"
)

Schema = dict[str, Any]
IDENTIFIER = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")


def _union(parts: list[str]) -> str:
    unique = list(dict.fromkeys(parts))
    return " | ".join(unique) if unique else "never"


def _wrap(text: str) -> str:
    return f"({text})" if " | " in text else text


def _type(schema: Schema) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return _union([json.dumps(value) for value in schema["enum"]])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return _union([_type(part) for part in schema[key]])
    if "allOf" in schema and len(schema["allOf"]) == 1:
        return _type(schema["allOf"][0])
    kind = schema.get("type")
    if isinstance(kind, list):
        return _union([_type({**schema, "type": one}) for one in kind])
    match kind:
        case "string":
            return "string"
        case "integer" | "number":
            return "number"
        case "boolean":
            return "boolean"
        case "null":
            return "null"
        case "array":
            if "prefixItems" in schema:
                items = ", ".join(_type(item) for item in schema["prefixItems"])
                return f"[{items}]"
            return f"{_wrap(_type(schema.get('items', {})))}[]"
        case "object":
            if "properties" in schema:
                return _object(schema, "")
            extra = schema.get("additionalProperties")
            value = _type(extra) if isinstance(extra, dict) else "unknown"
            return f"Record<string, {value}>"
        case _:
            return "unknown"


def _object(schema: Schema, indent: str) -> str:
    # A model's answer carries every field, defaults included, so none is optional.
    lines = ["{"]
    for name, field in schema["properties"].items():
        key = name if IDENTIFIER.fullmatch(name) else json.dumps(name)
        lines.append(f"{indent}  {key}: {_type(field)};")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def _comment(schema: Schema) -> str:
    # A docstring's own "*/" must not end the comment early.
    text = " ".join(str(schema.get("description", "")).split()).replace("*/", "*\\/")
    return f"/** {text} */\n" if text else ""


def generate() -> str:
    # Field names, not aliases: the routes dump their models without by_alias.
    _, top = models_json_schema(
        [(model, "serialization") for model in MODELS],
        by_alias=False,
        ref_template="#/$defs/{model}",
    )
    # Two models of one name get module-qualified names, which no one means to import.
    clashes = sorted(name for name in top["$defs"] if "__" in name)
    if clashes:
        raise SystemExit(f"two response models share a name; rename one: {', '.join(clashes)}")
    parts = [HEADER]
    for name, schema in sorted(top["$defs"].items()):
        parts.append("\n" + _comment(schema))
        if schema.get("type") == "object" and "properties" in schema:
            parts.append(f"export interface {name} {_object(schema, '')}\n")
        else:
            parts.append(f"export type {name} = {_type(schema)};\n")
    return "".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the browser's API types.")
    parser.add_argument("--check", action="store_true", help="fail when the file is stale")
    check = parser.parse_args().check
    text = generate()
    if check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run scripts/generate_api_types.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
