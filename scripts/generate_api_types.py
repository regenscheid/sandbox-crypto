"""Generate the browser's TypeScript types for the workspace API's typed answers.

The workspace's response models (Pydantic) are the API contract. This script turns
their JSON Schema, in serialization mode, into ``web/workspace/src/lib/api-types.ts``.
Run ``uv run python scripts/generate_api_types.py`` after changing a response model.
With ``--check``, as the workspace tests run it, the script changes nothing and fails
when the committed file differs from what it would generate.

Only the schema features the models use are translated: objects, arrays, tuples,
enums, constants, unions, nullable values and references. Every field is required,
since a model's answer carries its defaults too. Constraints such as lengths and
patterns stay on the server.
"""

